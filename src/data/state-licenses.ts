const tables: Record<string, Record<string, StateLicenseFact>> = {
  collection,
  lending,
  "money-transmitters": moneyTransmitters,
  mortgage,
};

export function getStateLicense(stateSlug: string, licenseSlug: LicenseSlug): StateLicenseFact | undefined {
  return tables[licenseSlug]?.[stateSlug];
}

export function getFactsForLicense(licenseSlug: LicenseSlug): { stateSlug: string; fact: StateLicenseFact }[] {
  const table = tables[licenseSlug];
  if (!table) return [];
  return Object.entries(table).map(([stateSlug, fact]) => ({ stateSlug, fact }));
}

export function getFactsForState(stateSlug: string): { licenseSlug: LicenseSlug; fact: StateLicenseFact }[] {
  return (["collection", "lending", "money-transmitters", "mortgage"] as LicenseSlug[])
    .map((licenseSlug) => {
      const item = tables[licenseSlug]?.[stateSlug];
      return item ? { licenseSlug, fact: item } : undefined;
    })
    .filter((row): row is { licenseSlug: LicenseSlug; fact: StateLicenseFact } => Boolean(row));
}
